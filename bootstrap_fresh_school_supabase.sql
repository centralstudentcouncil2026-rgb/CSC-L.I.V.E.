create or replace function public.app_profile_role(user_id uuid)
returns text
language sql
stable
security definer
set search_path = public
as $$
    select lower(trim(coalesce(role, '')))
    from public.user_profiles
    where id = user_id
    limit 1
$$;

create or replace function public.app_profile_is_approved(user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(lower(trim(approval_status)) = 'approved', false)
    from public.user_profiles
    where id = user_id
    limit 1
$$;

create or replace function public.app_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(
        public.app_profile_role(auth.uid()) = 'admin'
        and public.app_profile_is_approved(auth.uid()),
        false
    )
$$;

create or replace function public.app_is_dashboard_user()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(
        public.app_profile_role(auth.uid()) in ('admin', 'committee')
        and public.app_profile_is_approved(auth.uid()),
        false
    )
$$;

create or replace function public.app_can_read_conversation(conversation_uuid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.conversations conversation_record
        where conversation_record.id = conversation_uuid
          and auth.uid() in (conversation_record.created_by, conversation_record.receiver_id)
    )
$$;

create or replace function public.app_can_send_conversation_message(
    conversation_uuid uuid,
    message_receiver uuid
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.conversations conversation_record
        where conversation_record.id = conversation_uuid
          and (
              (auth.uid() = conversation_record.created_by and message_receiver = conversation_record.receiver_id)
              or
              (auth.uid() = conversation_record.receiver_id and message_receiver = conversation_record.created_by)
          )
    )
$$;

-- Controlled RPC workflows --------------------------------------------------

create or replace function public.save_pending_user_profile(
    p_email text,
    p_full_name text,
    p_mobile_number text,
    p_role text,
    p_assigned_sport_id jsonb default null,
    p_assigned_sport_name text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
set row_security = off
as $$
declare
    current_user_id uuid := auth.uid();
    normalized_role text := lower(trim(coalesce(p_role, '')));
    authenticated_email text := lower(trim(coalesce(auth.jwt() ->> 'email', '')));
    resolved_sport_id bigint;
    resolved_sport_name text := nullif(trim(coalesce(p_assigned_sport_name, '')), '');
begin
    if current_user_id is null then
        raise exception 'You must be logged in to create a profile.';
    end if;

    if normalized_role not in ('admin', 'committee') then
        raise exception 'Invalid dashboard role.';
    end if;

    if authenticated_email = ''
       or authenticated_email <> lower(trim(coalesce(p_email, ''))) then
        raise exception 'The authenticated email does not match the registered account.';
    end if;

    if p_assigned_sport_id is not null and p_assigned_sport_id <> 'null'::jsonb then
        resolved_sport_id := trim(both '"' from p_assigned_sport_id::text)::bigint;
    end if;

    if normalized_role = 'committee' and resolved_sport_id is null and resolved_sport_name is null then
        raise exception 'Committee accounts must choose a sport assignment.';
    end if;

    if normalized_role = 'committee' and lower(coalesce(resolved_sport_name, '')) = 'overall committee' then
        raise exception 'Overall Committee access can only be assigned by an admin.';
    end if;

    insert into public.user_profiles (
        id, email, full_name, mobile_number, role, approval_status,
        reviewed_at, reviewed_by, assigned_sport_id, assigned_sport_name
    )
    values (
        current_user_id, trim(p_email), trim(p_full_name), trim(p_mobile_number),
        normalized_role, 'pending', null, null, resolved_sport_id, resolved_sport_name
    )
    on conflict (id)
    do update set
        email = excluded.email,
        full_name = excluded.full_name,
        mobile_number = excluded.mobile_number,
        role = excluded.role,
        assigned_sport_id = excluded.assigned_sport_id,
        assigned_sport_name = excluded.assigned_sport_name
    where lower(trim(public.user_profiles.approval_status)) = 'pending';

    return current_user_id;
end
$$;

create or replace function public.admin_set_account_approval_status(
    target_user_id uuid,
    next_status text
)
returns void
language plpgsql
security definer
set search_path = public
set row_security = off
as $$
declare
    normalized_status text := lower(trim(coalesce(next_status, '')));
begin
    if not public.app_is_admin() then
        raise exception 'Only an approved admin can update account approvals.';
    end if;

    if target_user_id = auth.uid() then
        raise exception 'You cannot change the approval status of the account currently signed in.';
    end if;

    if normalized_status not in ('approved', 'hold', 'suspended') then
        raise exception 'Invalid account approval status.';
    end if;

    update public.user_profiles
    set approval_status = normalized_status, reviewed_at = now(), reviewed_by = auth.uid()
    where id = target_user_id;

    if not found then
        raise exception 'Account profile not found.';
    end if;
end
$$;

