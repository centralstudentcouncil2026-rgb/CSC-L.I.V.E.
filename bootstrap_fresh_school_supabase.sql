-- Fresh-school bootstrap for the CSC L.I.V.E. web application.
-- Run once in a NEW Supabase project's SQL Editor.
-- This creates an empty application database. It does not copy CSC data.
--
-- After running this file:
-- 1. Update SUPABASE_URL and SUPABASE_ANON_KEY in index.html,
--    AdminDashboard.html, CommitteeDashboard.html, and StudentDashboard.html.
-- 2. Register the first admin through index.html.
-- 3. Promote that first admin in the SQL Editor with:
--      update public.user_profiles
--      set approval_status = 'approved'
--      where lower(email) = lower('FIRST_ADMIN_EMAIL');
-- 4. Create teams and sports from the admin dashboard.

begin;

create extension if not exists pgcrypto;

-- Core tournament tables ----------------------------------------------------

create table if not exists public.sports (
    id bigint generated by default as identity primary key,
    sport_name text not null unique,
    points_per_game numeric(12, 2) not null default 0 check (points_per_game >= 0),
    winner_points numeric(12, 2) not null default 0 check (winner_points >= 0),
    loser_points numeric(12, 2) not null default 0 check (loser_points >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.sports_leaderboard (
    id bigint generated by default as identity primary key,
    team text not null unique,
    points numeric(12, 2) not null default 0,
    wins integer not null default 0,
    losses integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.participants (
    id bigint generated by default as identity primary key,
    name text not null,
    student_id text not null unique,
    team text not null,
    status text not null default 'Pending'
        check (status in ('Approved', 'Pending', 'Rejected')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.attendance (
    id bigint generated by default as identity primary key,
    participant_id bigint references public.participants(id) on delete set null,
    student_id text not null,
    participant_name text not null default '',
    team text not null default '',
    status text not null default 'Present',
    attendance_date date not null default current_date,
    checked_at timestamptz not null default now(),
    unique (student_id, attendance_date)
);

create table if not exists public.scheduled_matches (
    id bigint generated by default as identity primary key,
    sport_id bigint not null references public.sports(id),
    team_one_id bigint not null references public.sports_leaderboard(id),
    team_two_id bigint not null references public.sports_leaderboard(id),
    match_time timestamptz not null,
    location text not null default '',
    status text not null default 'Next'
        check (status in ('Next', 'Ongoing', 'Done')),
    match_stage text not null default 'regular'
        check (match_stage in ('regular', 'semifinals', 'finals', 'battle_for_third')),
    game_period integer check (game_period is null or game_period between 1 and 5),
    timer_enabled boolean not null default false,
    timer_duration_seconds integer not null default 600
        check (timer_duration_seconds >= 0),
    timer_started_at timestamptz,
    created_by text not null,
    created_by_role text not null default 'committee',
    created_by_name text not null default '',
    delete_requested boolean not null default false,
    delete_requested_at timestamptz,
    delete_requested_by text,
    delete_requested_by_name text,
    delete_approved boolean not null default false,
    delete_approved_at timestamptz,
    delete_approved_by text,
    delete_rejected boolean not null default false,
    delete_rejected_at timestamptz,
    delete_rejected_by text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (team_one_id <> team_two_id)
);

create table if not exists public.game_history (
    id bigint generated by default as identity primary key,
    match_id bigint not null unique references public.scheduled_matches(id) on delete cascade,
    sport_id bigint references public.sports(id) on delete set null,
    sport_name text,
    team_one_id bigint references public.sports_leaderboard(id) on delete set null,
    team_two_id bigint references public.sports_leaderboard(id) on delete set null,
    team_one_name text,
    team_two_name text,
    winner_team_id bigint references public.sports_leaderboard(id) on delete set null,
    winner_team_name text,
    loser_team_id bigint references public.sports_leaderboard(id) on delete set null,
    loser_team_name text,
    winner_points_awarded numeric(12, 2) not null default 0,
    loser_points_awarded numeric(12, 2) not null default 0,
    best_player text,
    match_time timestamptz,
    location text not null default '',
    result text,
    declared_at timestamptz not null default now(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Public notices and student feedback --------------------------------------

create table if not exists public.announcements (
    id bigint generated by default as identity primary key,
    title text not null,
    message text not null,
    audience text not null default 'all'
        check (audience in ('all', 'students', 'committee')),
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.student_feedback (
    id bigint generated by default as identity primary key,
    feedback_type text not null
        check (lower(trim(feedback_type)) in ('recommendation', 'concern')),
    student_name text,
    student_id text,
    contact_info text,
    message text not null,
    status text not null default 'New'
        check (status in ('New', 'Reviewed')),
    reviewed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Dashboard accounts and messaging ----------------------------------------

create table if not exists public.user_profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    email text not null unique,
    full_name text not null,
    mobile_number text not null default '',
    role text not null check (lower(trim(role)) in ('admin', 'committee')),
    approval_status text not null default 'pending'
        check (lower(trim(approval_status)) in ('pending', 'approved', 'hold', 'suspended', 'rejected')),
    assigned_sport_id bigint references public.sports(id) on delete set null,
    assigned_sport_name text,
    reviewed_at timestamptz,
    reviewed_by uuid,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.conversations (
    id uuid primary key default gen_random_uuid(),
    created_by uuid not null references auth.users(id) on delete cascade,
    receiver_id uuid not null references auth.users(id) on delete cascade,
    sender_role text not null check (lower(trim(sender_role)) in ('admin', 'committee')),
    receiver_role text not null check (lower(trim(receiver_role)) in ('admin', 'committee')),
    status text not null default 'open',
    last_message text,
    last_message_at timestamptz,
    unread_count_sender integer not null default 0,
    unread_count_receiver integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (created_by <> receiver_id)
);

create table if not exists public.messages (
    id uuid primary key default gen_random_uuid(),
    conversation_id uuid not null references public.conversations(id) on delete cascade,
    sender_id uuid not null references auth.users(id) on delete cascade,
    sender_role text not null check (lower(trim(sender_role)) in ('admin', 'committee')),
    receiver_id uuid not null references auth.users(id) on delete cascade,
    receiver_role text not null check (lower(trim(receiver_role)) in ('admin', 'committee')),
    message_text text,
    attachment_url text,
    attachment_path text,
    is_read boolean not null default false,
    created_at timestamptz not null default now(),
    check (length(trim(coalesce(message_text, ''))) > 0 or attachment_url is not null)
);

create table if not exists public.conversation_user_settings (
    conversation_id uuid not null references public.conversations(id) on delete cascade,
    user_id uuid not null references auth.users(id) on delete cascade,
    hidden_at timestamptz,
    primary key (conversation_id, user_id)
);

create index if not exists scheduled_matches_status_time_idx
on public.scheduled_matches (status, match_time);
create index if not exists game_history_declared_at_idx
on public.game_history (declared_at desc);
create index if not exists attendance_date_idx
on public.attendance (attendance_date, checked_at desc);
create index if not exists conversations_users_idx
on public.conversations (created_by, receiver_id, last_message_at desc);
create index if not exists messages_conversation_created_idx
on public.messages (conversation_id, created_at);

-- General timestamp triggers ------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at := now();
    return new;
end
$$;

create or replace function public.sync_sport_winner_points()
returns trigger
language plpgsql
as $$
begin
    new.winner_points := new.points_per_game;
    return new;
end
$$;

drop trigger if exists sync_sport_winner_points on public.sports;
create trigger sync_sport_winner_points
before insert or update of points_per_game on public.sports
for each row execute function public.sync_sport_winner_points();

do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'sports',
        'sports_leaderboard',
        'participants',
        'scheduled_matches',
        'game_history',
        'announcements',
        'student_feedback',
        'user_profiles',
        'conversations'
    ]
    loop
        execute format('drop trigger if exists set_updated_at on public.%I', table_name);
        execute format(
            'create trigger set_updated_at before update on public.%I for each row execute function public.set_updated_at()',
            table_name
        );
    end loop;
end
$$;

create or replace function public.update_conversation_after_message()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    update public.conversations
    set
        last_message = coalesce(new.message_text, case when new.attachment_url is not null then 'Photo' else '' end),
        last_message_at = new.created_at,
        unread_count_sender = case
            when new.receiver_id = created_by then unread_count_sender + 1
            else unread_count_sender
        end,
        unread_count_receiver = case
            when new.receiver_id = receiver_id then unread_count_receiver + 1
            else unread_count_receiver
        end
    where id = new.conversation_id;

    return new;
end
$$;

drop trigger if exists update_conversation_after_message on public.messages;
create trigger update_conversation_after_message
after insert on public.messages
for each row execute function public.update_conversation_after_message();

