-- Locked attendance point logs from August 16, 2026 onward.
-- Run this in Supabase SQL Editor. It leaves attendance before 2026-08-16 untouched.

create table if not exists public.attendance_point_logs (
    id bigint generated by default as identity primary key,
    attendance_date date not null,
    session_title text not null,
    team text not null,
    total_present integer not null default 0,
    registered_player_count integer not null default 0,
    student_player_count integer not null default 0,
    faculty_count integer not null default 0,
    department_chair_count integer not null default 0,
    dean_count integer not null default 0,
    student_from_college_count integer not null default 0,
    sponsor_count integer not null default 0,
    sponsor_game_attendance_count integer not null default 0,
    total_students numeric not null default 0,
    total_faculty numeric not null default 0,
    total_department_chairs numeric not null default 0,
    registered_player_points numeric not null default 5,
    student_player_points numeric not null default 0,
    faculty_points numeric not null default 5,
    department_chair_points numeric not null default 100,
    dean_points numeric not null default 50,
    sponsor_points numeric not null default 5,
    sponsor_game_attendance_points numeric not null default 15,
    total_points numeric not null default 0,
    point_settings jsonb not null default '{}'::jsonb,
    locked_at timestamptz not null default now(),
    source text not null default 'refresh_attendance_point_log'
);

alter table public.attendance_point_logs
    add column if not exists attendance_date date,
    add column if not exists session_title text,
    add column if not exists team text,
    add column if not exists total_present integer not null default 0,
