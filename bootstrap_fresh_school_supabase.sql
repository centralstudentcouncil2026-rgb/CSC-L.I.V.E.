create policy "Public can read scheduled matches"
on public.scheduled_matches for select to anon, authenticated using (true);
create policy "Dashboard users can create matches"
on public.scheduled_matches for insert to authenticated
with check (
    public.app_is_dashboard_user()
    and (public.app_is_admin() or created_by = auth.uid()::text)
);
create policy "Admins can update all matches"
on public.scheduled_matches for update to authenticated
using (public.app_is_admin()) with check (public.app_is_admin());
create policy "Committee can update own matches"
on public.scheduled_matches for update to authenticated
using (
    public.app_profile_role(auth.uid()) = 'committee'
    and public.app_profile_is_approved(auth.uid())
    and created_by = auth.uid()::text
)
with check (
    public.app_profile_role(auth.uid()) = 'committee'
    and public.app_profile_is_approved(auth.uid())
    and created_by = auth.uid()::text
);
create policy "Admins can delete matches"
on public.scheduled_matches for delete to authenticated using (public.app_is_admin());

create policy "Public can read game history"
on public.game_history for select to anon, authenticated using (true);
create policy "Dashboard users can create owned game history"
on public.game_history for insert to authenticated
with check (
    public.app_is_admin()
    or (
        public.app_profile_role(auth.uid()) = 'committee'
        and public.app_profile_is_approved(auth.uid())
        and exists (
            select 1 from public.scheduled_matches match_record
            where match_record.id = game_history.match_id
              and match_record.created_by = auth.uid()::text
        )
    )
);
create policy "Dashboard users can update owned game history"
on public.game_history for update to authenticated
using (
    public.app_is_admin()
    or exists (
        select 1 from public.scheduled_matches match_record
        where match_record.id = game_history.match_id
          and match_record.created_by = auth.uid()::text
          and public.app_profile_role(auth.uid()) = 'committee'
          and public.app_profile_is_approved(auth.uid())
    )
)
with check (
    public.app_is_admin()
    or exists (
        select 1 from public.scheduled_matches match_record
        where match_record.id = game_history.match_id
          and match_record.created_by = auth.uid()::text
          and public.app_profile_role(auth.uid()) = 'committee'
          and public.app_profile_is_approved(auth.uid())
    )
);
